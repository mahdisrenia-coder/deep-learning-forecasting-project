# ============================================================
# DATA LOADER
# ============================================================
# This file defines PyTorch Dataset classes for loading time series data.
#
# Each dataset class:
#   1. Loads data from CSV (local or Hugging Face)
#   2. Scales/normalizes the data
#   3. Creates time features (month, day, weekday, hour, etc.)
#   4. Provides sliding windows for training
#
# The sliding window is the key concept:
#   seq_len  = number of past points to look at (input)
#   label_len = overlap between input and output
#   pred_len  = number of future points to predict (output)
#
# Example: seq_len=96, label_len=48, pred_len=96
#   |←────── seq_len ──────→|← label_len →|←─ pred_len ─→|
#   |─────────────────────|──────────────|───────────────|
#   s_begin               s_end         r_begin       r_end
# ============================================================

import os
import numpy as np
import pandas as pd
import torch
from datasets import load_dataset  # For downloading from Hugging Face Hub
from torch.utils.data import Dataset, DataLoader
from sklearn.preprocessing import StandardScaler  # For normalization
from utils.timefeatures import time_features  # Advanced time feature encoding
from utils.augmentation import run_augmentation_single
import warnings
warnings.filterwarnings('ignore')

# Hugging Face repository where datasets are stored
HUGGINGFACE_REPO = "thuml/Time-Series-Library"


class Dataset_ETT_hour(Dataset):
    """
    Dataset class for ETT (Electricity Transformer Temperature) data at HOURLY frequency.
    Datasets: ETTh1, ETTh2 (2-hour interval)
    
    The ETT dataset has fixed splits:
      - Train: first 12 months
      - Validation: next 4 months
      - Test: last 4 months
    """
    
    def __init__(self, args, root_path, flag='train', size=None,
                 features='S', data_path='ETTh1.csv',
                 target='OT', scale=True, timeenc=0, freq='h', seasonal_patterns=None):
        """
        Initialize the dataset.
        
        Args:
            args: Command-line arguments (hyperparameters, etc.)
            root_path: Path to the dataset folder
            flag: 'train', 'val', or 'test'
            size: [seq_len, label_len, pred_len] - sliding window sizes
            features: 'M' (multivariate), 'S' (univariate), 'MS' (multivariate with target)
            data_path: CSV filename
            target: Target column name
            scale: Whether to normalize the data
            timeenc: 0=simple time features, 1=advanced time features
            freq: Data frequency ('h' for hourly)
            seasonal_patterns: For M4 dataset (unused)
        """
        # size [seq_len, label_len, pred_len]
        self.args = args
        
        # Set default sequence lengths if not provided
        if size == None:
            self.seq_len = 24 * 4 * 4   # 384 (16 days of hourly data)
            self.label_len = 24 * 4     # 96
            self.pred_len = 24 * 4      # 96
        else:
            self.seq_len = size[0]
            self.label_len = size[1]
            self.pred_len = size[2]
        
        # Determine which split to load (train=0, val=1, test=2)
        assert flag in ['train', 'test', 'val']
        type_map = {'train': 0, 'val': 1, 'test': 2}
        self.set_type = type_map[flag]
        
        # Store configuration
        self.features = features
        self.target = target
        self.scale = scale
        self.timeenc = timeenc
        self.freq = freq
        
        self.root_path = root_path
        self.data_path = data_path
        
        # Load and preprocess the data
        self.__read_data__()

    def __read_data__(self):
        """
        Load the data from CSV (local or Hugging Face),
        scale it, create time features, and split into train/val/test.
        """
        self.scaler = StandardScaler()
        
        # Try to load local CSV; if not found, download from Hugging Face
        local_fp = os.path.join(self.root_path, self.data_path)
        cfg_name = os.path.splitext(os.path.basename(self.data_path))[0]
        
        if os.path.exists(local_fp):
            df_raw = pd.read_csv(local_fp)
        else:
            ds = load_dataset(HUGGINGFACE_REPO, name=cfg_name)
            df_raw = ds["train"].to_pandas()
        
        # ETT-specific splits: 12 months train, 4 months val, 4 months test
        # border1s and border2s define the start and end of each split
        # The '- self.seq_len' accounts for the sliding window offset
        border1s = [0, 12 * 30 * 24 - self.seq_len, 12 * 30 * 24 + 4 * 30 * 24 - self.seq_len]
        border2s = [12 * 30 * 24, 12 * 30 * 24 + 4 * 30 * 24, 12 * 30 * 24 + 8 * 30 * 24]
        border1 = border1s[self.set_type]
        border2 = border2s[self.set_type]
        
        # Select data columns based on features type
        if self.features == 'M' or self.features == 'MS':
            # 'M': Use all feature columns
            cols_data = df_raw.columns[1:]
            df_data = df_raw[cols_data]
        elif self.features == 'S':
            # 'S': Use only the target column
            df_data = df_raw[[self.target]]
        
        # Scale the data (fit on training data only to avoid data leakage)
        if self.scale:
            train_data = df_data[border1s[0]:border2s[0]]
            self.scaler.fit(train_data.values)
            data = self.scaler.transform(df_data.values)
        else:
            data = df_data.values
        
        # Extract time features (month, day, weekday, hour)
        df_stamp = df_raw[['date']][border1:border2]
        df_stamp['date'] = pd.to_datetime(df_stamp.date)
        
        if self.timeenc == 0:
            # Simple time features: month, day, weekday, hour
            df_stamp['month'] = df_stamp.date.apply(lambda row: row.month, 1)
            df_stamp['day'] = df_stamp.date.apply(lambda row: row.day, 1)
            df_stamp['weekday'] = df_stamp.date.apply(lambda row: row.weekday(), 1)
            df_stamp['hour'] = df_stamp.date.apply(lambda row: row.hour, 1)
            data_stamp = df_stamp.drop(['date'], 1).values
        elif self.timeenc == 1:
            # Advanced time features using `time_features()`
            data_stamp = time_features(pd.to_datetime(df_stamp['date'].values), freq=self.freq)
            data_stamp = data_stamp.transpose(1, 0)
        
        # Store the data for this split
        self.data_x = data[border1:border2]
        self.data_y = data[border1:border2]
        self.data_stamp = data_stamp
        
        # Data augmentation (if enabled and in training mode)
        if self.set_type == 0 and self.args.augmentation_ratio > 0:
            from utils.augmentation import run_augmentation_single
            self.data_x, self.data_y, augmentation_tags = run_augmentation_single(
                self.data_x, self.data_y, self.args
            )

    def __getitem__(self, index):
        """
        Return a single sliding window sample.
        
        The sliding window:
            |←────── seq_x ──────→|← label_len →|←─ pred_len ─→|
            |─────────────────────|──────────────|───────────────|
            s_begin               s_end         r_begin       r_end
        
        Returns:
            seq_x: Input sequence (past time steps)
            seq_y: Output sequence (future time steps)
            seq_x_mark: Time features for input
            seq_y_mark: Time features for output
        """
        s_begin = index
        s_end = s_begin + self.seq_len
        r_begin = s_end - self.label_len
        r_end = r_begin + self.label_len + self.pred_len
        
        seq_x = self.data_x[s_begin:s_end]
        seq_y = self.data_y[r_begin:r_end]
        seq_x_mark = self.data_stamp[s_begin:s_end]
        seq_y_mark = self.data_stamp[r_begin:r_end]
        
        return seq_x, seq_y, seq_x_mark, seq_y_mark

    def __len__(self):
        """
        Number of possible sliding windows.
        """
        return len(self.data_x) - self.seq_len - self.pred_len + 1

    def inverse_transform(self, data):
        """
        Reverse the normalization (convert back to original scale).
        Useful for interpreting predictions.
        """
        return self.scaler.inverse_transform(data)


